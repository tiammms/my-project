/**
 * Interface language: Russian (default) or Kazakh.
 *
 * Screen texts are written as tr("русский", "қазақша") right where they are shown.
 * Texts produced by the analysis core (reasons, advice, report lines) are kept in Russian in the history,
 * so the same record reads the same everywhere, and are translated only when shown: [core].
 * A line that has no translation is shown in Russian (never left empty).
 *
 * The Kazakh texts were written by the team and must be reviewed by a native speaker before release.
 */
object I18n {
    @Volatile var kk: Boolean = false

    fun core(s: String?): String {
        if (s == null) return ""
        if (!kk || s.isBlank()) return s
        return translate(s) ?: s
    }

    private fun translate(s: String): String? {
        exact(s)?.let { return it }
        for ((rx, f) in TEMPLATES) rx.matchEntire(s)?.let { m -> return f(m) }
        // "Label: value" and "a; b" — translate the parts
        for (sep in listOf("; ", ": ")) {
            val i = s.indexOf(sep)
            if (i > 0) {
                val parts = if (sep == "; ") s.split(sep) else listOf(s.substring(0, i), s.substring(i + sep.length))
                val tr = parts.map { translate(it) }
                if (tr.any { it != null }) return parts.indices.joinToString(sep) { tr[it] ?: parts[it] }
            }
        }
        return null
    }

    /** Case of the first letter is kept: "В разговоре: просят код…" uses the lower-case form of a title. */
    private fun exact(s: String): String? {
        val t = s.trim()
        val k = LOWER[t.lowercase()] ?: return null
        return if (t.first().isLowerCase()) k.replaceFirstChar { it.lowercase() } else k
    }

